/** Hook: journey-page strings in the active shared language. */
export function useJourney() {
  const { lang } = useT();
  const t = (key: JourneyKey) => catalogs[lang][key] ?? en[key];
  return { t, lang };
}

/** CAD currency: $1,249,000 (en) · 1 249 000 $ (fr-CA). */
export function formatCad(value: number, lang: Lang): string {
  const grouped = value.toLocaleString(lang === 'fr' ? 'fr-CA' : 'en-CA');
  return lang === 'fr' ? `${grouped}\u00A0$` : `$${grouped}`;
}

/** Compact money: $1.25M / 1,25 M$ */
export function formatCadCompact(value: number, lang: Lang): string {
  if (value >= 1_000_000) {
    const m = (value / 1_000_000).toLocaleString(lang === 'fr' ? 'fr-CA' : 'en-CA', {
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    });
    return lang === 'fr' ? `${m}\u00A0M$` : `$${m}M`;
  }
  return formatCad(value, lang);
}

/** Short date: Jun 10, 2025 / 10 juin 2025 */
export function formatDate(d: Date | string, lang: Lang): string {
  const date = typeof d === 'string' ? new Date(d) : d;
  return date.toLocaleDateString(lang === 'fr' ? 'fr-CA' : 'en-CA', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  });
}

/** Relative age label: "2h ago" / "il y a 2 h" (demo resolution: hours/days). */
export function relativeAge(d: Date | string, lang: Lang): string {
  const date = typeof d === 'string' ? new Date(d) : d;
  const hours = Math.max(0, Math.round((Date.now() - date.getTime()) / 3_600_000));
  if (hours < 24) return lang === 'fr' ? `il y a ${hours} h` : `${hours}h ago`;
  const days = Math.round(hours / 24);
  return lang === 'fr' ? `il y a ${days} j` : `${days}d ago`;
}
