const catalogs: Record<Lang, Record<GovernanceKey, string>> = { en, fr };

export type GovernanceVars = Record<string, string | number>;

/** Pure translator — used by the Seller Portal, which owns its FR-first
 * language toggle independently of the app-shell language. */
export function translateGovernance(lang: Lang, key: GovernanceKey, vars?: GovernanceVars): string {
  let s = catalogs[lang][key] ?? en[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export interface Governance {
  lang: Lang;
  t: (key: GovernanceKey, vars?: GovernanceVars) => string;
  dfLocale: Locale;
}

/** Page-scoped translator riding on the shell i18n context. */
export function useGovernanceT(): Governance {
  const { lang } = useT();
  const t = (key: GovernanceKey, vars?: GovernanceVars) => translateGovernance(lang, key, vars);
  return { lang, t, dfLocale: lang === 'fr' ? frCA : enCA };
}
