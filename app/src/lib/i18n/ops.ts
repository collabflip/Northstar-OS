const catalogs: Record<Lang, Record<OpsKey, string>> = { en, fr };

export type OpsVars = Record<string, string | number>;

export interface Ops {
  lang: Lang;
  t: (key: OpsKey, vars?: OpsVars) => string;
  dfLocale: Locale;
}

/** Page-scoped translator riding on the shell i18n context. */
export function useOps(): Ops {
  const { lang } = useT();
  const t = (key: OpsKey, vars?: OpsVars) => {
    let s = catalogs[lang][key] ?? en[key];
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    }
    return s;
  };
  return { lang, t, dfLocale: lang === 'fr' ? frCA : enCA };
}
